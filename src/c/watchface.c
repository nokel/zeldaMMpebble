/* =========================================================
   ARCH DRAW
   -------------------------------------------------------
   pdc_transform_gdraw_command_image_draw_transformed()
   derives scale10 from ARCH_SCALE vs. the PDC's native
   bounding-box width so the arch renders at exactly
   ARCH_SCALE × ARCH_SCALE pixels regardless of what size
   the original .pdc was authored at.

   It makes an internal copy of s_arch_cmd each frame, so
   the master image is never mutated.
========================================================= */

static void arch_update_proc(Layer *layer, GContext *ctx) {

  if (!s_arch_cmd) return;

  /* Get the native size baked into the PDC file. */
  GSize native = gdraw_command_image_get_bounds_size(s_arch_cmd);

  /* Compute scale as ×10 integer (e.g. 1.0 → 10, 1.5 → 15).
     Guard against a zero native size just in case the asset is bad. */
  int scale10 = (native.w > 0)
    ? (ARCH_SCALE * 10) / native.w
    : 10;

  /* Draw at (0,0) relative to the layer — the layer itself is
     positioned by rect_pos() in window_load().
     Pass GColorClear for colors to keep the PDC's own colors.
     Pass 0 for stroke_width to keep the PDC's own widths.      */
  pdc_transform_gdraw_command_image_draw_transformed(
    ctx,
    s_arch_cmd,
    GPoint(0, 0),   /* offset inside the layer */
    scale10,        /* scale ×10 */
    0,              /* rotation (degrees, 0 = none) */
    GColorClear,    /* fill_color override  — Clear = use PDC original */
    GColorClear,    /* stroke_color override — Clear = use PDC original */
    0               /* stroke_width override — 0 = use PDC original */
  );
}

/* =========================================================
   HEART LOOKUP
========================================================= */

static GBitmap *heart_bitmap(int level) {

  switch (level) {
    case 4:  return s_heart_full_bmp;
    case 3:  return s_heart_3quarter_bmp;
    case 2:  return s_heart_half_bmp;
    case 1:  return s_heart_quarter_bmp;
    default: return s_heart_empty_bmp;
  }
}

/* =========================================================
   UPDATE HEARTS FROM BATTERY
========================================================= */

static void update_hearts(int battery_percent) {
  /*
     Battery expressed as 40 quarter-subunits (10 hearts × 4 levels).
     Fill order: indices 0..4 = top row left→right,
                          5..9 = bottom row left→right.

     Remainder mapping (how many quarter-subunits are in the partial heart):
       remainder 3 → quarterheart  (level 1)
       remainder 2 → halfheart     (level 2)
       remainder 1 → 3quarterheart (level 3)
       remainder 0 → empty         (level 0)
  */

  int total_subunits = (battery_percent * 40) / 100;
  int full_hearts    = total_subunits / 4;
  int remainder      = total_subunits % 4;

  for (int i = 0; i < 10; i++) {

    if (i < full_hearts) {

      bitmap_layer_set_bitmap(s_hearts[i], heart_bitmap(4));

    } else if (i == full_hearts) {

      int level;
      switch (remainder) {
        case 3:  level = 1; break;
        case 2:  level = 2; break;
        case 1:  level = 3; break;
        default: level = 0; break;
      }
      bitmap_layer_set_bitmap(s_hearts[i], heart_bitmap(level));

    } else {
      bitmap_layer_set_bitmap(s_hearts[i], heart_bitmap(0));
    }
  }
}

/* =========================================================
   BATTERY CALLBACK
========================================================= */

static void battery_callback(BatteryChargeState state) {
  update_hearts(state.charge_percent);
}

/* =========================================================
   UPDATE TIME
========================================================= */

static void arch_ellipse_pos(int angle_deg, int *out_x, int *out_y) {
  GRect bounds = layer_get_bounds(window_get_root_layer(s_window));
  int center_x = ARCH_X + ARCH_SCALE / 2;
  int center_y = bounds.size.h - MOVE_ALL_Y;
  int radius_x = (ARCH_SCALE * 45) / 100;
  int radius_y = ((bounds.size.h - 2 * MOVE_ALL_Y - ARCH_Y) * 10) / 13;

  int32_t angle = DEG_TO_TRIGANGLE(angle_deg);
  *out_x = center_x + (radius_x * cos_lookup(angle)) / TRIG_MAX_RATIO;
  *out_y = center_y - (radius_y * sin_lookup(angle)) / TRIG_MAX_RATIO;
}

static void update_sun_moon(int hour_24, int minute) {
  bool is_day = (hour_24 >= 6 && hour_24 < 18);
  int angle_deg;

  if (is_day) {
    // Sun: right (0°) at 6am → top (90°) at noon → left (180°) at 6pm
    int mins = (hour_24 - 6) * 60 + minute;
    angle_deg = mins / 4;
  } else {
    // Moon: right (0°) at 6pm → top (90°) at midnight → left (180°) at 6am
    int mins = (hour_24 >= 18) ? (hour_24 - 18) * 60 + minute
                                : (hour_24 + 6) * 60 + minute;
    angle_deg = mins / 4;
  }

  int x, y;
  arch_ellipse_pos(angle_deg, &x, &y);

  int icon_w = 18;
  int icon_h = is_day ? 18 : 20;
  bitmap_layer_set_bitmap(s_sun_moon_layer, is_day ? s_hour_sun_bmp : s_moon_hour_bmp);
  layer_set_frame(bitmap_layer_get_layer(s_sun_moon_layer),
                  rect_pos(x - icon_w / 2, y - icon_h / 2, icon_w, icon_h));
}

// Positions the sunsecond icon at the given trig-domain angle.
// Radii are 80% of the main arc (tighter ellipse).
// angle uses the same 0x0000–0xFFFF scale as cos_lookup / sin_lookup per
// https://developer.repebble.com/docs/c/Foundation/Math/
// (TRIG_MAX_RATIO = 0xFFFF is the max return value; TRIG_MAX_ANGLE = 0x10000
// represents a full 360° rotation.)
static void update_sun_second(int32_t angle) {
  GRect bounds = layer_get_bounds(window_get_root_layer(s_window));
  int center_x = ARCH_X + ARCH_SCALE / 2;
  int center_y = bounds.size.h - MOVE_ALL_Y;
  int radius_x = (ARCH_SCALE * 45 * 8) / 1000;
  int radius_y = ((bounds.size.h - 2 * MOVE_ALL_Y - ARCH_Y) * 80) / 130;

  int x = center_x + (radius_x * cos_lookup(angle)) / TRIG_MAX_RATIO;
  int y = center_y - (radius_y * sin_lookup(angle)) / TRIG_MAX_RATIO;

  layer_set_frame(bitmap_layer_get_layer(s_sun_second_layer),
                  rect_pos(x - 8, y - 8, 16, 16));
}

static void update_time(void) {

  time_t       temp      = time(NULL);
  struct tm   *tick_time = localtime(&temp);

  static char hour_buffer[3];
  static char minute_buffer[3];
  static char date_buffer[16];
  static char day_buffer[16];

  int hour = tick_time->tm_hour;

  if (!config_24h) {
    hour = hour % 12;
    if (hour == 0) hour = 12;
  }

  snprintf(hour_buffer,   sizeof(hour_buffer),   "%d",    hour);
  snprintf(minute_buffer, sizeof(minute_buffer),  "%02d",  tick_time->tm_min);

  snprintf(date_buffer,   sizeof(date_buffer),
           "%d/%d",
           tick_time->tm_mday,
           tick_time->tm_mon + 1);

  const char *days[] = {
    "SUN","MON","TUE","WED","THU","FRI","SAT"
  };
  const char *months[] = {
    "JAN","FEB","MAR","APR","MAY","JUN",
    "JUL","AUG","SEP","OCT","NOV","DEC"
  };

  snprintf(day_buffer, sizeof(day_buffer),
           "%s %s",
           days[tick_time->tm_wday],
           months[tick_time->tm_mon]);

  text_layer_set_text(s_hour_layer,   hour_buffer);
  text_layer_set_text(s_minute_layer, minute_buffer);
  text_layer_set_text(s_date_layer,   date_buffer);
  text_layer_set_text(s_day_layer,    day_buffer);

  update_sun_moon(tick_time->tm_hour, tick_time->tm_min);
}

/* =========================================================
   SUN-SECOND ANIMATION
   -------------------------------------------------------
   AppTimer-based sweep: fires every ANIM_INTERVAL_MS and
   interpolates the angle linearly.  AppTimers fire in both
   bright and dim display modes, so behaviour is consistent
   regardless of the backlight state.
========================================================= */

#define ANIM_INTERVAL_MS 33u  /* ~30 fps */

static void anim_timer_cb(void *context) {
  s_anim_timer = NULL;
  s_anim_fire_count++;
  uint32_t elapsed = s_anim_fire_count * ANIM_INTERVAL_MS;

  int32_t start_a = DEG_TO_TRIGANGLE(180 - s_anim_start_sec * 3);
  int32_t end_a   = DEG_TO_TRIGANGLE(180 - (s_anim_start_sec + 1) * 3);

  if (elapsed >= config_anim_duration) {
    update_sun_second(end_a);
    return;
  }

  int32_t angle = start_a + (int32_t)((int64_t)(end_a - start_a)
                             * elapsed / config_anim_duration);
  update_sun_second(angle);
  s_anim_timer = app_timer_register(ANIM_INTERVAL_MS, anim_timer_cb, NULL);
}

static void start_sec_animation(int second) {
  if (!s_in_focus) return;

  if (s_anim_timer) {
    app_timer_cancel(s_anim_timer);
    s_anim_timer = NULL;
  }

  s_anim_start_sec = second;
  s_anim_fire_count = 0;
  update_sun_second(DEG_TO_TRIGANGLE(180 - second * 3));

  if (!config_anim_enabled || config_anim_duration == 0) return;

  s_anim_timer = app_timer_register(ANIM_INTERVAL_MS, anim_timer_cb, NULL);
}

/* =========================================================
   TICK
========================================================= */

static void tick_handler(struct tm *tick_time, TimeUnits units_changed) {
  // Always refresh hours/minutes — calling on every second is cheap because
  // TextLayer only triggers a redraw when the string content actually changes.
  // Relying solely on MINUTE_UNIT misses stale-time cases on some Rebble builds.
  update_time();
  start_sec_animation(tick_time->tm_sec);
}

/* =========================================================
   SUNSECOND VISIBILITY TIMER
   -------------------------------------------------------
   app_focus_service fires for notifications but NOT when
   the Pebble backlight simply times out from inactivity.
   A countdown timer is the only reliable cross-firmware
   way to hide the icon after a configurable idle period.
========================================================= */

static void hide_sun_second(void) {
  s_in_focus = false;
  if (s_anim_timer) {
    app_timer_cancel(s_anim_timer);
    s_anim_timer = NULL;
  }
  layer_set_hidden(bitmap_layer_get_layer(s_sun_second_layer), true);
}

static void timeout_cb(void *context) {
  s_timeout_timer = NULL;
  hide_sun_second();
}

// Call whenever the sunsecond should (re)appear and the countdown should reset.
static void show_sun_second(void) {
  if (s_timeout_timer) {
    app_timer_cancel(s_timeout_timer);
    s_timeout_timer = NULL;
  }
  s_in_focus = true;
  layer_set_hidden(bitmap_layer_get_layer(s_sun_second_layer), false);
  if (config_timeout_s > 0) {
    s_timeout_timer = app_timer_register(config_timeout_s * 1000,
                                         timeout_cb, NULL);
  }
}

static void focus_handler(bool in_focus) {
  if (in_focus) {
    // Notification dismissed / system UI gone — reset the countdown.
    show_sun_second();
    update_time();
    time_t now = time(NULL);
    struct tm *t = localtime(&now);
    start_sec_animation(t->tm_sec);
  } else {
    // Notification / system UI covering the watchface — hide immediately.
    hide_sun_second();
    if (s_timeout_timer) {
      app_timer_cancel(s_timeout_timer);
      s_timeout_timer = NULL;
    }
  }
}

