/* =========================================================
   WINDOW UNLOAD
========================================================= */

static void window_unload(Window *window) {

  if (s_timeout_timer) {
    app_timer_cancel(s_timeout_timer);
    s_timeout_timer = NULL;
  }
  if (s_anim_timer) {
    app_timer_cancel(s_anim_timer);
    s_anim_timer = NULL;
  }

  text_layer_destroy(s_hour_layer);
  text_layer_destroy(s_minute_layer);
  text_layer_destroy(s_date_layer);
  text_layer_destroy(s_day_layer);
#if defined(PBL_HEALTH)
  text_layer_destroy(s_hr_layer);
#endif

  bitmap_layer_destroy(s_green_circle);
  bitmap_layer_destroy(s_blue_circle);

  for (int i = 0; i < 10; i++) {
    bitmap_layer_destroy(s_hearts[i]);
  }

  bitmap_layer_destroy(s_leftc_layer);
  bitmap_layer_destroy(s_rightc_layer);
  bitmap_layer_destroy(s_downc_layer);

  bitmap_layer_destroy(s_speed_layer);
  bitmap_layer_destroy(s_magic_layer);
  bitmap_layer_destroy(s_sun_moon_layer);
  bitmap_layer_destroy(s_sun_second_layer);
  bitmap_layer_destroy(s_wallet_layer);

#if defined(PBL_HEALTH)
  for (int i = 0; i < s_steps_digit_count; i++) {
    bitmap_layer_destroy(s_steps_digits[i]);
  }
#endif

  layer_destroy(s_arch_layer);

  unload_resources();
}

/* =========================================================
   SETTINGS — persistent storage + AppMessage
========================================================= */

static void load_settings(void) {
  if (persist_exists(PERSIST_KEY_24H))
    config_24h = persist_read_bool(PERSIST_KEY_24H);
  if (persist_exists(PERSIST_KEY_ANIM_ENABLED))
    config_anim_enabled = persist_read_bool(PERSIST_KEY_ANIM_ENABLED);
  if (persist_exists(PERSIST_KEY_ANIM_DURATION))
    config_anim_duration = (uint32_t)persist_read_int(PERSIST_KEY_ANIM_DURATION);
  if (persist_exists(PERSIST_KEY_TIMEOUT_S))
    config_timeout_s = (uint32_t)persist_read_int(PERSIST_KEY_TIMEOUT_S);
}

static void inbox_received_handler(DictionaryIterator *iter, void *context) {
  Tuple *t;

  t = dict_find(iter, MESSAGE_KEY_KEY_24H);
  if (t) {
    config_24h = (bool)t->value->int32;
    persist_write_bool(PERSIST_KEY_24H, config_24h);
  }

  t = dict_find(iter, MESSAGE_KEY_KEY_ANIM_ENABLED);
  if (t) {
    config_anim_enabled = (bool)t->value->int32;
    persist_write_bool(PERSIST_KEY_ANIM_ENABLED, config_anim_enabled);
  }

  t = dict_find(iter, MESSAGE_KEY_KEY_ANIM_DURATION);
  if (t) {
    config_anim_duration = (uint32_t)t->value->int32;
    persist_write_int(PERSIST_KEY_ANIM_DURATION, (int32_t)config_anim_duration);
  }

  t = dict_find(iter, MESSAGE_KEY_KEY_TIMEOUT_S);
  if (t) {
    config_timeout_s = (uint32_t)t->value->int32;
    persist_write_int(PERSIST_KEY_TIMEOUT_S, (int32_t)config_timeout_s);
  }

  // Refresh display with new settings.
  update_time();
  time_t now = time(NULL);
  struct tm *t2 = localtime(&now);
  start_sec_animation(t2->tm_sec);
}

/* =========================================================
   INIT
========================================================= */

static void init(void) {

  load_settings();

  s_window = window_create();

  window_set_window_handlers(s_window, (WindowHandlers) {
    .load   = window_load,
    .unload = window_unload,
  });

  window_stack_push(s_window, true);

  tick_timer_service_subscribe(SECOND_UNIT, tick_handler);
  battery_state_service_subscribe(battery_callback);
  app_focus_service_subscribe(focus_handler);
#if defined(PBL_HEALTH)
  health_service_events_subscribe(health_handler, NULL);
#endif

  app_message_register_inbox_received(inbox_received_handler);
  app_message_open(128, 128);
}

/* =========================================================
   DEINIT
========================================================= */

static void deinit(void) {

  tick_timer_service_unsubscribe();
  battery_state_service_unsubscribe();
  app_focus_service_unsubscribe();
#if defined(PBL_HEALTH)
  health_service_events_unsubscribe();
#endif
  window_destroy(s_window);
}

/* =========================================================
   MAIN
========================================================= */

int main(void) {
  init();
  app_event_loop();
  deinit();
}
